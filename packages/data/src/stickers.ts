export const isSticker = (n: unknown): n is number =>
  typeof n === 'number' && Number.isInteger(n) && n >= 0 && n < STICKERS.length;

// Cached for a year (next.config.ts): bump the version when the pictures change.
const file = (n: number) => `/art/stickers/${String(n).padStart(2, '0')}`;
export const stickerSrc = (n: number) => `${file(n)}.webp?v=1`;
/** The picker's small still, so a page of 119 stickers doesn't play them all at once. */
export const stickerStill = (n: number) => `${file(n)}-s.webp?v=1`;
